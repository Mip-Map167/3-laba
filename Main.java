public class Main {
    public static void main(String[] args) {
        // Создаем двумерный массив размером 3x3
        int[][] array = {
                {25, 2, 30},
                {6, 10, 8},
                {11, 12, 40}
        };

        // Выводим исходный массив на экран
        System.out.println("Исходный массив:");
        for (int i = 0; i < 3; i++) { // Перебираем строки
            for (int j = 0; j < 3; j++) { // Перебираем столбцы
                System.out.print(array[i][j] + " "); // Выводим элемент
            }
            System.out.println(); // Переход на новую строку
        }

        // Сортируем главную диагональ методом вставок
        for (int i = 1; i < 3; i++) {
            int temp = array[i][i]; // Запоминаем текущий элемент диагонали
            int j = i - 1;

            // Двигаем элементы, пока не найдем нужное место для temp
            while (j >= 0 && array[j][j] > temp) {
                array[j + 1][j + 1] = array[j][j]; // Сдвигаем элемент вправо
                j--;
            }
            array[j + 1][j + 1] = temp; // Вставляем элемент на нужное место
        }

        // Выводим массив после сортировки диагонали
        System.out.println("После сортировки диагонали:");
        for (int i = 0; i < 3; i++) { // Перебираем строки
            for (int j = 0; j < 3; j++) { // Перебираем столбцы
                System.out.print(array[i][j] + " "); // Выводим элемент
            }
            System.out.println(); // Переход на новую строку
        }
    }
}